// `prettier` does not yet support `import type`

import type React from "react";
import {useCallback, useEffect, useMemo, useRef, useSyncExternalStore} from "react";

type URLState = [URL, (value: React.SetStateAction<URL>, noHistoryEntry?: boolean) => void];

interface PendingUrlUpdate {
    url: URL;
    shouldPush: boolean;
}

/** Scalar parameter result: value, React setter, and whether the key is repeated. */
type ScalarUrlParamResult = [string | undefined, React.Dispatch<React.SetStateAction<string | undefined>>, boolean];
/** Map parameter result: value, React setter, and duplicated subkeys in first-repeat order. */
type MapUrlParamResult = [
    ReadonlyMap<string, string> | undefined,
    React.Dispatch<React.SetStateAction<ReadonlyMap<string, string> | undefined>>,
    readonly string[],
];

// `info` is not persisted in history; it only identifies the navigate event
// synchronously generated by this hook.
const browserUrlNavigationInfo = {};

function getBrowserUrl(): string {
    return window.navigation.currentEntry?.url ?? window.location.href;
}

function subscribeToBrowserUrl(onStoreChange: () => void): () => void {
    window.navigation.addEventListener("currententrychange", onStoreChange);
    return () => window.navigation.removeEventListener("currententrychange", onStoreChange);
}

export function useBrowserUrl(): URLState {
    const href = useSyncExternalStore(subscribeToBrowserUrl, getBrowserUrl);
    const url = useMemo(() => new URL(href), [href]);
    const pendingUrlUpdate = useRef<PendingUrlUpdate | undefined>(undefined);

    useEffect(() => {
        const listener = (event: NavigateEvent) => {
            if (event.canIntercept && event.info === browserUrlNavigationInfo) {
                // These navigations only update URL-backed state. Preserve the user's
                // current focus and scroll position while making them same-document.
                event.intercept({
                    focusReset: "manual",
                    scroll: "manual",
                });
            }
        };
        window.navigation.addEventListener("navigate", listener);
        return () => window.navigation.removeEventListener("navigate", listener);
    }, []);
    const setUrl = useCallback((action: React.SetStateAction<URL>, noHistoryEntry?: boolean) => {
        let pending = pendingUrlUpdate.current;
        if (!pending) {
            pending = {
                url: new URL(getBrowserUrl()),
                shouldPush: false,
            };
            pendingUrlUpdate.current = pending;
            queueMicrotask(() => {
                const update = pendingUrlUpdate.current;
                pendingUrlUpdate.current = undefined;
                if (update && update.url.href !== getBrowserUrl()) {
                    window.navigation.navigate(update.url.toString(), {
                        history: update.shouldPush ? "push" : "replace",
                        info: browserUrlNavigationInfo,
                    });
                }
            });
        }
        pending.url = typeof action === "function" ? action(pending.url) : action;
        pending.shouldPush ||= !noHistoryEntry;
    }, []);
    return [url, setUrl];
}

export interface UrlParamOptions {
    history?: "push" | "replace";
}
function useUrlParamInternal<T>(
    urlState: URLState,
    key: string,
    history: "push" | "replace",
    matches: (parameter: string, key: string) => boolean,
    read: (params: URLSearchParams, key: string) => [T, string[]],
    encode: (key: string, value: T) => [string, string][],
): [T, React.Dispatch<React.SetStateAction<T>>, readonly string[]] {
    const [url, setUrl] = urlState;
    const searchParams = new URLSearchParams(url.hash.slice(1));
    // Memoize the result using only the relevant property subset.
    // Memoizing makes sure maps keep stable object references if other unrelated parameters changed,
    // thereby avoiding unnecessary React re-rendering / recomputations.
    const groupEntries = [...searchParams].filter(([param]) => matches(param, key));
    const groupToken = new URLSearchParams(groupEntries).toString();
    const parsed = useMemo(() => {
        const params = new URLSearchParams(groupToken);
        return read(params, key);
    }, [groupToken, key, read]);
    const set = useCallback(
        (action: React.SetStateAction<T>) => {
            setUrl((url) => {
                const searchParams = new URLSearchParams(url.hash.slice(1));
                const [currentValue] = read(searchParams, key);
                const newValue = typeof action === "function" ? (action as (value: T) => T)(currentValue) : action;
                const nextEntries = encode(key, newValue);
                const existing = [...searchParams].filter(([param]) => matches(param, key));
                if (url.search === "" && new URLSearchParams(existing).toString() === new URLSearchParams(nextEntries).toString())
                    return url;
                for (const param of [...searchParams.keys()]) {
                    if (matches(param, key)) searchParams.delete(param);
                }
                for (const [param, value] of nextEntries) searchParams.append(param, value);
                // Keep app state in the fragment so it is never sent to the server.
                const newURL = new URL(url);
                newURL.search = "";
                const serialized = searchParams.toString();
                newURL.hash = serialized ? `#${serialized}` : "";
                return newURL;
            }, history === "replace");
        },
        [setUrl, key, matches, history, read, encode],
    );
    return [parsed[0], set, parsed[1]];
}

/**
 * Reads and writes one hash parameter. Missing or duplicated parameters return undefined;
 * identical repeated values are duplicates too. The third tuple item reports whether the key
 * is duplicated.
 */
export function useUrlParam(urlState: URLState, key: string, options: UrlParamOptions = {}): ScalarUrlParamResult {
    const [value, set, duplicateKeys] = useUrlParamInternal(
        urlState,
        key,
        options.history ?? "push",
        isScalarParam,
        readScalarParam,
        encodeScalarParam,
    );
    return [value, set, duplicateKeys.length > 0];
}

function readScalarParam(params: URLSearchParams, key: string): [string | undefined, string[]] {
    const values = params.getAll(key);
    return [values.length === 1 ? values[0] : undefined, values.length > 1 ? [key] : []];
}

function isScalarParam(key: string, parameter: string): boolean {
    return key === parameter;
}

function encodeScalarParam(key: string, value: string | undefined): [string, string][] {
    return value === undefined ? [] : [[key, value]];
}

/**
 * Reads and writes bracketed hash parameters for a group. Missing groups return an empty Map;
 * duplicate subkeys make the value undefined and are listed once in first-repeat order.
 */
export function useUrlMapParam(urlState: URLState, key: string, options: UrlParamOptions = {}): MapUrlParamResult {
    return useUrlParamInternal(urlState, key, options.history ?? "push", isMapParam, readMapParam, encodeMapParam);
}

function isMapParam(key: string, group: string): boolean {
    return key.startsWith(`${group}[`) && key.endsWith("]");
}

function readMapParam(params: URLSearchParams, group: string): [ReadonlyMap<string, string> | undefined, string[]] {
    const map = new Map<string, string>();
    const duplicates: string[] = [];
    const seenDuplicates = new Set<string>();
    for (const [key, value] of params) {
        if (!isMapParam(key, group)) continue;
        const name = key.slice(group.length + 1, -1);
        if (map.has(name)) {
            if (!seenDuplicates.has(name)) {
                duplicates.push(name);
                seenDuplicates.add(name);
            }
        } else {
            map.set(name, value);
        }
    }
    return [duplicates.length ? undefined : map, duplicates];
}

function encodeMapParam(key: string, value: ReadonlyMap<string, string> | undefined): [string, string][] {
    return value ? [...value].map(([name, entry]) => [`${key}[${name}]`, entry]) : [];
}
